import ExcelJS from "exceljs";
import { afterAll, beforeEach, describe, expect, it } from "vitest";
import { buildTemplateWorkbook, getTemplate } from "@manga/core/collection";
import { handleParseSubmission, type ObjectReader } from "../src/jobs/parse-submission";
import { db, makeDeps, resetDatabase, shutdown } from "./helpers";

const SECRET = "t".repeat(40);
const day = (y: number, m: number, d: number) => new Date(Date.UTC(y, m - 1, d));

class MemoryReader implements ObjectReader {
  objects = new Map<string, Uint8Array>();
  failures = 0;
  async read(key: string) {
    if (this.failures > 0) {
      this.failures -= 1;
      throw new Error("STORAGE_DOWN");
    }
    const object = this.objects.get(key);
    if (!object) throw new Error("NoSuchKey");
    return object;
  }
}

async function seed() {
  const prospect = await db().prospect.create({ data: { companyName: "Groupe A", companyNameNorm: "groupe a", sector: "Restauration", source: "MANUEL", status: "CLIENT" } });
  const client = await db().client.create({ data: { prospectId: prospect.id, legalName: "Groupe A" } });
  const entity = await db().entity.create({ data: { clientId: client.id, name: "Resto A", sector: "RESTAURATION" } });
  const plan = await db().collectionPlan.create({ data: { entityId: entity.id, templateId: "resto_mensuel", startsOn: day(2026, 1, 1) } });
  return { client, entity, plan };
}

async function period(planId: string, month: number, status: "EN_CONTROLE" | "VALIDE" = "EN_CONTROLE") {
  return db().collectionPeriod.create({
    data: { planId, periodStart: day(2026, month, 1), periodEnd: day(2026, month + 1, 0), dueAt: day(2026, month + 1, 3), status },
  });
}

/** Template generated by the platform, then filled in. */
async function file(entityId: string, periodRow: { id: string; periodStart: Date; periodEnd: Date; dueAt: Date }, values: (number | undefined)[] = [10_000_000, 3_000_000, 2_500_000, 2_000_000, 1_000]) {
  const base = await buildTemplateWorkbook({
    template: getTemplate("resto_mensuel")!,
    entity: { id: entityId, name: "Resto A" },
    period: { id: periodRow.id, start: periodRow.periodStart, end: periodRow.periodEnd, dueAt: periodRow.dueAt },
    secret: SECRET,
  });
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.load(base as unknown as ArrayBuffer);
  values.forEach((v, i) => (wb.getWorksheet("Saisie_Restaurant")!.getCell(2, i + 1).value = v));
  return Buffer.from(await wb.xlsx.writeBuffer());
}

let sequence = 0;
async function submit(reader: MemoryReader, periodId: string, bytes: Uint8Array, version = 1) {
  sequence += 1;
  const key = `clients/test/${sequence}.xlsx`;
  reader.objects.set(key, bytes);
  return db().submission.create({
    data: { periodId, version, templateId: "resto_mensuel", templateVersion: 1, storageKey: key, originalName: "depot.xlsx", sizeBytes: bytes.length, checksum: "x", uploadedBy: "user-1", status: "EN_CONTROLE" },
  });
}

beforeEach(resetDatabase);
afterAll(shutdown);

describe("collection.parse-submission", () => {
  it("validates a correct file: report, normalised rows, row count, submission and period in VALIDE", async () => {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, await file(entity.id, p));
    const { deps } = makeDeps();
    await handleParseSubmission({ submissionId: s.id }, { ...deps, storage: reader });

    const after = await db().submission.findUniqueOrThrow({ where: { id: s.id } });
    expect(after.status).toBe("VALIDE");
    expect(after.rowCount).toBe(1);
    expect((after.rows as { Saisie_Restaurant: unknown[] }).Saisie_Restaurant[0]).toMatchObject({ caHt: 10_000_000, nombreCouverts: 1000 });
    expect(after.report).toMatchObject({ errors: [], truncated: false });
    expect((await db().collectionPeriod.findUniqueOrThrow({ where: { id: p.id } })).status).toBe("VALIDE");
  });

  it("rejects a badly filled file with the errors in the report, and keeps what was read", async () => {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, await file(entity.id, p, [undefined, 3_000_000, 2_500_000, 2_000_000]));
    await handleParseSubmission({ submissionId: s.id }, { ...makeDeps().deps, storage: reader });

    const after = await db().submission.findUniqueOrThrow({ where: { id: s.id } });
    expect(after.status).toBe("REJETE");
    expect(after.rowCount).toBeNull();
    const report = after.report as { errors: { code: string; row: number; message: string }[] };
    expect(report.errors[0]).toMatchObject({ code: "REQUIRED", row: 2 });
    expect(report.errors[0]!.message).toContain("Ligne 2");
    expect((await db().collectionPeriod.findUniqueOrThrow({ where: { id: p.id } })).status).toBe("REJETE");
  });

  it("rejects a file made for another period (wrong month)", async () => {
    const { entity, plan } = await seed();
    const october = await period(plan.id, 10);
    const november = await period(plan.id, 11, "VALIDE");
    const reader = new MemoryReader();
    const s = await submit(reader, october.id, await file(entity.id, november));
    await handleParseSubmission({ submissionId: s.id }, { ...makeDeps().deps, storage: reader });
    const after = await db().submission.findUniqueOrThrow({ where: { id: s.id } });
    expect(after.status).toBe("REJETE");
    expect((after.report as { errors: { code: string }[] }).errors.map((e) => e.code)).toEqual(["META_WRONG_PERIOD"]);
  });

  it("rejects a file made for another entity (wrong hotel)", async () => {
    const { client, plan } = await seed();
    const other = await db().entity.create({ data: { clientId: client.id, name: "Resto B", sector: "RESTAURATION" } });
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, await file(other.id, p));
    await handleParseSubmission({ submissionId: s.id }, { ...makeDeps().deps, storage: reader });
    expect(((await db().submission.findUniqueOrThrow({ where: { id: s.id } })).report as { errors: { code: string }[] }).errors.map((e) => e.code)).toEqual(["META_WRONG_ENTITY"]);
  });

  it("rejects a file that is not a workbook (renamed text) without crashing the job", async () => {
    const { plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, Buffer.from("not an excel file at all, just text padding here"));
    await handleParseSubmission({ submissionId: s.id }, { ...makeDeps().deps, storage: reader });
    const after = await db().submission.findUniqueOrThrow({ where: { id: s.id } });
    expect(after.status).toBe("REJETE");
    expect((after.report as { errors: { code: string }[] }).errors[0]!.code).toBe("NOT_A_ZIP");
  });

  it("warns about coherence with the previous accepted month, without rejecting", async () => {
    const { entity, plan } = await seed();
    const september = await period(plan.id, 9, "VALIDE");
    const reader = new MemoryReader();
    const previous = await submit(reader, september.id, Buffer.from("x"));
    await db().submission.update({ where: { id: previous.id }, data: { status: "VALIDE", rows: { Saisie_Restaurant: [{ caHt: 1 }] } } });

    const october = await period(plan.id, 10);
    const s = await submit(reader, october.id, await file(entity.id, october));
    await handleParseSubmission({ submissionId: s.id }, { ...makeDeps().deps, storage: reader });
    expect((await db().submission.findUniqueOrThrow({ where: { id: s.id } })).status).toBe("VALIDE");
  });

  it("is idempotent: a submission already checked is left alone", async () => {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, await file(entity.id, p));
    const deps = { ...makeDeps().deps, storage: reader };
    await handleParseSubmission({ submissionId: s.id }, deps);
    const first = await db().submission.findUniqueOrThrow({ where: { id: s.id } });
    reader.objects.clear(); // a second run would fail if it read the file again
    await handleParseSubmission({ submissionId: s.id }, deps);
    expect(await db().submission.findUniqueOrThrow({ where: { id: s.id } })).toEqual(first);
    await expect(handleParseSubmission({ submissionId: "does-not-exist" }, deps)).resolves.toBeUndefined();
  });

  it("leaves a period alone when it is no longer waiting for this check (forced meanwhile)", async () => {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    await db().collectionPeriod.update({ where: { id: p.id }, data: { status: "ACCEPTE_AVEC_RESERVE" } });
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, await file(entity.id, p));
    await handleParseSubmission({ submissionId: s.id }, { ...makeDeps().deps, storage: reader });
    expect((await db().collectionPeriod.findUniqueOrThrow({ where: { id: p.id } })).status).toBe("ACCEPTE_AVEC_RESERVE");
  });

  it("retries on a storage failure, and gives up on the last attempt with a technical error", async () => {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, await file(entity.id, p));
    const deps = { ...makeDeps().deps, storage: reader };

    reader.failures = 1;
    await expect(handleParseSubmission({ submissionId: s.id }, deps)).rejects.toThrow("STORAGE_DOWN");
    expect((await db().submission.findUniqueOrThrow({ where: { id: s.id } })).status).toBe("EN_CONTROLE");

    reader.failures = 1;
    await handleParseSubmission({ submissionId: s.id, finalAttempt: true }, deps);
    const after = await db().submission.findUniqueOrThrow({ where: { id: s.id } });
    expect(after.status).toBe("ERREUR_TECHNIQUE");
    // The deposit can be retried: the period is open again.
    expect((await db().collectionPeriod.findUniqueOrThrow({ where: { id: p.id } })).status).toMatch(/ATTENDU|EN_RETARD/);
  });

  it("gives an overdue period back as EN_RETARD", async () => {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, await file(entity.id, p));
    reader.failures = 1;
    await handleParseSubmission({ submissionId: s.id, finalAttempt: true }, { ...makeDeps({ now: () => day(2026, 12, 1) }).deps, storage: reader });
    expect((await db().collectionPeriod.findUniqueOrThrow({ where: { id: p.id } })).status).toBe("EN_RETARD");
  });

  it("marks an unknown template as a technical error instead of looping", async () => {
    const { plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const s = await submit(reader, p.id, Buffer.from("x"));
    await db().submission.update({ where: { id: s.id }, data: { templateId: "removed_template" } });
    await handleParseSubmission({ submissionId: s.id }, { ...makeDeps().deps, storage: reader });
    expect((await db().submission.findUniqueOrThrow({ where: { id: s.id } })).status).toBe("ERREUR_TECHNIQUE");
  });
});

describe("rejection notifications", () => {
  async function rejectedDeposit(uploadedBy: string, existingRejections = 0) {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    for (let v = 1; v <= existingRejections; v++) {
      const old = await submit(reader, p.id, Buffer.from("x"), v);
      await db().submission.update({ where: { id: old.id }, data: { status: "REJETE" } });
    }
    const s = await submit(reader, p.id, await file(entity.id, p, [undefined, 3_000_000, 2_500_000, 2_000_000]), existingRejections + 1);
    await db().submission.update({ where: { id: s.id }, data: { uploadedBy } });
    return { s, reader };
  }

  it("emails the depositor straight away with the first errors and a link", async () => {
    const user = await db().user.create({ data: { email: "awa@resto.ci", name: "Awa Koné", role: "CLIENT_CONTRIBUTEUR" } });
    const { s, reader } = await rejectedDeposit(user.id);
    const { deps, queue } = makeDeps();
    await handleParseSubmission({ submissionId: s.id }, { ...deps, storage: reader });

    expect(queue.emails).toHaveLength(1);
    const { job, dedupeKey } = queue.emails[0]!;
    expect(dedupeKey).toBe(`collection-rejected:${s.id}`);
    expect(job.to).toBe("awa@resto.ci");
    expect(job.template === "collection-rejected" && job.data).toMatchObject({ name: "Awa Koné", entityName: "Resto A", periodLabel: "octobre 2026", errorCount: 1, url: "https://app.example.com/espace-client/collecte" });
    expect(job.template === "collection-rejected" && job.data.firstErrors[0]).toContain("Ligne 2");
    expect(queue.fanouts).toHaveLength(0);
  });

  it("does not email a valid deposit, a disabled user, an admin or an unknown depositor", async () => {
    const { entity, plan } = await seed();
    const p = await period(plan.id, 10);
    const reader = new MemoryReader();
    const valid = await submit(reader, p.id, await file(entity.id, p));
    const ok = makeDeps();
    await handleParseSubmission({ submissionId: valid.id }, { ...ok.deps, storage: reader });
    expect(ok.queue.emails).toHaveLength(0);

    const disabled = await db().user.create({ data: { email: "off@resto.ci", name: "Off", role: "CLIENT_CONTRIBUTEUR", disabledAt: new Date() } });
    const admin = await db().user.create({ data: { email: "admin@cabinet.ci", name: "Admin", role: "ADMIN" } });
    for (const uploadedBy of [disabled.id, admin.id, "ghost"]) {
      const { s, reader: r } = await rejectedDeposit(uploadedBy);
      const d = makeDeps();
      await handleParseSubmission({ submissionId: s.id }, { ...d.deps, storage: r });
      expect(d.queue.emails).toHaveLength(0);
      await resetDatabase();
    }
  });

  it("warns the consultant from the third rejection on the same period", async () => {
    const user = await db().user.create({ data: { email: "awa@resto.ci", name: "Awa", role: "CLIENT_CONTRIBUTEUR" } });
    const second = await rejectedDeposit(user.id, 1);
    const d2 = makeDeps();
    await handleParseSubmission({ submissionId: second.s.id }, { ...d2.deps, storage: second.reader });
    expect(d2.queue.fanouts).toHaveLength(0); // 2 rejections

    await resetDatabase();
    const user3 = await db().user.create({ data: { email: "awa@resto.ci", name: "Awa", role: "CLIENT_CONTRIBUTEUR" } });
    const third = await rejectedDeposit(user3.id, 2);
    const d3 = makeDeps();
    await handleParseSubmission({ submissionId: third.s.id }, { ...d3.deps, storage: third.reader });
    expect(d3.queue.fanouts).toHaveLength(1);
    const fanout = d3.queue.fanouts[0]!;
    expect(fanout.job).toMatchObject({ type: "COLLECTION_REPEATED_REJECTION", audience: "ADMINS" });
    const email = fanout.job.email!;
    expect(email.to).toBe("admin@example.com");
    expect(email.template === "collection-repeated-rejection" && email.data).toMatchObject({ clientName: "Groupe A", entityName: "Resto A", rejections: 3, adminUrl: "https://app.example.com/admin/collecte" });
  });

  it("keeps the result even if the notification cannot be queued", async () => {
    const user = await db().user.create({ data: { email: "awa@resto.ci", name: "Awa", role: "CLIENT_CONTRIBUTEUR" } });
    const { s, reader } = await rejectedDeposit(user.id);
    const { deps, queue } = makeDeps();
    const failing = Object.assign(Object.create(queue), { enqueueEmail: async () => { throw new Error("queue down"); } });
    await expect(handleParseSubmission({ submissionId: s.id }, { ...deps, queue: failing, storage: reader })).resolves.toBeUndefined();
    expect((await db().submission.findUniqueOrThrow({ where: { id: s.id } })).status).toBe("REJETE");
  });
});
